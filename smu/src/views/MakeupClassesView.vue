<script setup>
import { ref, computed, watch } from 'vue'
import { useSessionStore } from '@/stores/session'
import { useDirectoryStore } from '@/stores/directory'
import { useAlertsStore } from '@/stores/alerts'
import { useReportsStore } from '@/stores/reports'
import { useSettingsStore } from '@/stores/settings'
import Modal from '@/components/common/Modal.vue'
import ConfirmDialog from '@/components/common/ConfirmDialog.vue'
import KpiCard from '@/components/common/KpiCard.vue'
import EmptyState from '@/components/common/EmptyState.vue'
import Pagination from '@/components/common/Pagination.vue'
import { useToast } from '@/composables/useToast'
import { fmtDate, todayISO, debounce } from '@/utils/format'
import { ALERT_THRESHOLDS } from '@/utils/constants'

const session   = useSessionStore()
const directory = useDirectoryStore()
const alerts    = useAlertsStore()
const reports   = useReportsStore()
const settings  = useSettingsStore()
const toast     = useToast()

const canManage = computed(() =>
  session.role === 'admin' || session.role === 'dept_head'
)

const scope = computed(() =>
  session.role === 'dept_head' ? session.department : null
)

const isAdmin = computed(() => session.role === 'admin')

/* ---------- Division options ---------- */
const DIVISIONS = [
  { value: '',          label: 'All divisions' },
  { value: 'Regular',   label: 'Regular' },
  { value: 'Extension', label: 'Extension' },
  { value: 'Both',      label: 'Both' }
]

function divisionOf(teacherId) {
  const t = directory.userById(teacherId)
  return t?.division || 'Regular'
}

/* ══════════════════════════════════════════════════
   ALL MAKEUP RECORDS
   ══════════════════════════════════════════════════ */
const rows = computed(() => {
  return alerts.makeupClasses
    .filter(x => {
      if (scope.value) return x.department === scope.value
      if (session.role === 'teacher') return x.teacherId === session.userId
      return true
    })
    .map(x => ({ ...x, division: x.division || divisionOf(x.teacherId) }))
    .sort((a, b) => new Date(b.createdAt || 0) - new Date(a.createdAt || 0))
})

/* ══════════════════════════════════════════════════
   NEEDS ATTENTION
   ══════════════════════════════════════════════════ */
const needsAttention = computed(() => {
  const teachers = directory.teachers.filter(t =>
    !scope.value || t.department === scope.value
  )

  return teachers
    .map(t => {
      const streak = alerts.consecutiveAbsences(t.id)
      const existing = rows.value.filter(m =>
        m.teacherId === t.id && m.status !== 'cancelled' && m.status !== 'completed'
      )
      const autoPending = existing.find(m => m.autoGenerated && m.status === 'pending')
      const scheduled   = existing.find(m => m.status === 'scheduled')

      if (autoPending) return { teacher: t, streak, record: autoPending, reason: 'auto' }
      if (streak >= ALERT_THRESHOLDS.deptHead && !scheduled && existing.length === 0) {
        return { teacher: t, streak, record: null, reason: 'no-record' }
      }
      return null
    })
    .filter(Boolean)
    .sort((a, b) => b.streak - a.streak)
})

const pendingRows   = computed(() => rows.value.filter(x => x.status === 'pending'))
const scheduledRows = computed(() =>
  rows.value.filter(x => x.status === 'scheduled')
    .sort((a, b) => String(a.makeupDate || '').localeCompare(String(b.makeupDate || '')))
)
const completedRows = computed(() => rows.value.filter(x => x.status === 'completed'))
const cancelledRows = computed(() => rows.value.filter(x => x.status === 'cancelled'))

const kpis = computed(() => ({
  needs:     needsAttention.value.length,
  scheduled: scheduledRows.value.length,
  completed: completedRows.value.length,
  cancelled: cancelledRows.value.length
}))

/* ══════════════════════════════════════════════════
   SCHEDULE MODAL
   ══════════════════════════════════════════════════ */
const scheduleOpen = ref(false)
const draft        = ref(null)

const draftDeptFilter = ref('')
const draftDivFilter  = ref('')

/* Teachers filtered by current Department + Division */
const filteredTeachers = computed(() => {
  let list = directory.teachers

  if (draftDeptFilter.value) {
    list = list.filter(t => t.department === draftDeptFilter.value)
  } else if (scope.value) {
    list = list.filter(t => t.department === scope.value)
  }

  if (draftDivFilter.value) {
    list = list.filter(t => {
      const d = t.division || 'Regular'
      if (draftDivFilter.value === 'Both') return d === 'Both'
      return d === draftDivFilter.value || d === 'Both'
    })
  }

  return list
})

function openScheduleFor(item) {
  const rec = item?.record || null
  const t   = item?.teacher || null

  draftDeptFilter.value = scope.value || ''
  draftDivFilter.value  = ''

  if (rec) {
    draft.value = {
      ...rec,
      division: rec.division || t?.division || divisionOf(rec.teacherId)
    }
    draftDeptFilter.value = rec.department || scope.value || ''
    draftDivFilter.value  = rec.division   || ''
  } else {
    draft.value = {
      id: null,
      teacherId: t?.id || '',
      department: t?.department || scope.value || '',
      division:   t?.division || 'Regular',
      course: '',
      originalDate: todayISO(),
      makeupDate: '',
      startTime: '',
      endTime: '',
      room: '',
      status: 'scheduled',
      studentsNotified: false,
      autoGenerated: false
    }
    if (t) {
      draftDeptFilter.value = t.department || ''
      draftDivFilter.value  = t.division   || ''
    }
  }

  scheduleOpen.value = true
}

function openManual() { openScheduleFor(null) }

function closeSchedule() {
  scheduleOpen.value = false
  draft.value = null
  draftDeptFilter.value = ''
  draftDivFilter.value = ''
}

/* When Department changes, reset teacher + division */
watch(draftDeptFilter, (newDept) => {
  if (!draft.value || draft.value.id) return
  draft.value.department = newDept || scope.value || ''
  draft.value.teacherId = ''
  draft.value.division = 'Regular'
})

/* When Division changes, reset teacher */
watch(draftDivFilter, () => {
  if (!draft.value || draft.value.id) return
  draft.value.teacherId = ''
})

/* When Teacher changes, auto-fill department + division */
watch(() => draft.value?.teacherId, (newId) => {
  if (!draft.value || !newId) return
  const t = directory.userById(+newId)
  if (!t) return
  draft.value.department = t.department || draft.value.department
  draft.value.division   = t.division || 'Regular'
})

function saveSchedule() {
  const d = draft.value
  const teacher = directory.userById(+d.teacherId)
  if (!teacher) { toast.err('Please choose a teacher'); return }
  if (!d.department) { toast.err('Please choose a department'); return }
  if (!d.course || !d.course.trim()) { toast.err('Please enter a course'); return }
  if (!d.makeupDate) { toast.err('Please choose a makeup date'); return }

  const payload = {
    teacherId: teacher.id,
    teacherName: teacher.name,
    department: d.department || teacher.department,
    division:   d.division || teacher.division || 'Regular',
    course: d.course.trim(),
    originalDate: d.originalDate,
    makeupDate: d.makeupDate,
    startTime: d.startTime,
    endTime: d.endTime,
    room: d.room.trim(),
    status: 'scheduled',
    studentsNotified: !!d.studentsNotified,
    autoGenerated: !!d.autoGenerated
  }

  if (d.id) {
    alerts.updateMakeupClass(d.id, payload)
    settings.audit('Schedule Makeup Class', 'Makeup Classes',
      `Accepted & scheduled for ${teacher.name}`)
    toast.ok(`Makeup class scheduled for ${teacher.name}`)
  } else {
    alerts.addMakeupClass(payload)
    settings.audit('Schedule Makeup Class', 'Makeup Classes',
      `Scheduled makeup for ${teacher.name}`)
    toast.ok(`Makeup class scheduled for ${teacher.name}`)
  }

  closeSchedule()
}

/* ══════════════════════════════════════════════════
   DISMISS
   ══════════════════════════════════════════════════ */
const dismissing = ref(null)

function askDismiss(item) { dismissing.value = item }

function confirmDismiss() {
  const item = dismissing.value
  if (!item) return
  if (item.record?.id) {
    alerts.updateMakeupClass(item.record.id, { status: 'cancelled' })
  }
  settings.audit('Dismiss Makeup Class', 'Makeup Classes',
    `Dismissed for ${item.teacher.name}`)
  toast.warn(`Makeup dismissed for ${item.teacher.name}`)
  dismissing.value = null
}

/* ══════════════════════════════════════════════════
   COMPLETE / CANCEL
   ══════════════════════════════════════════════════ */
function complete(row) {
  alerts.completeMakeupClass(row.id)
  settings.audit('Complete Makeup Class', 'Makeup Classes',
    `Completed for ${row.teacherName}`)
  toast.ok('Makeup class marked completed')
}

const cancelTarget = ref(null)
function askCancel(row) { cancelTarget.value = row }

function confirmCancel() {
  const row = cancelTarget.value
  if (!row) return
  alerts.updateMakeupClass(row.id, { status: 'cancelled' })
  settings.audit('Cancel Makeup Class', 'Makeup Classes',
    `Cancelled for ${row.teacherName}`)
  toast.warn('Makeup class cancelled')
  cancelTarget.value = null
}

/* ══════════════════════════════════════════════════
   HISTORY
   ══════════════════════════════════════════════════ */
const historyTab       = ref('all')
const historyQ         = ref('')
const historyDivFilter = ref('')

const historyRows = computed(() => {
  let list = rows.value
  if (historyTab.value !== 'all') list = list.filter(r => r.status === historyTab.value)

  if (historyDivFilter.value) {
    list = list.filter(r => {
      const d = r.division || 'Regular'
      if (historyDivFilter.value === 'Both') return d === 'Both'
      return d === historyDivFilter.value || d === 'Both'
    })
  }

  const term = historyQ.value.toLowerCase()
  if (term) {
    list = list.filter(r =>
      (r.teacherName + ' ' + r.course + ' ' + (r.room || '') + ' ' + r.department + ' ' + (r.division || ''))
        .toLowerCase().includes(term)
    )
  }
  return list
})

const historyPage     = ref(1)
const historyPageSize = ref(10)

const historyPageRows = computed(() => {
  const start = (historyPage.value - 1) * historyPageSize.value
  return historyRows.value.slice(start, start + historyPageSize.value)
})

function onHistorySize(v) { historyPageSize.value = v; historyPage.value = 1 }

const onHistorySearch = debounce(e => {
  historyQ.value = e.target.value
  historyPage.value = 1
}, 180)

watch(historyDivFilter, () => { historyPage.value = 1 })

/* ══════════════════════════════════════════════════
   PILLS + BADGES
   ══════════════════════════════════════════════════ */
function pillFor(status) {
  return {
    pending:   { cls: 'alert-warning',  label: 'Pending',   icon: 'hourglass-split' },
    scheduled: { cls: 'alert-info',     label: 'Scheduled', icon: 'calendar-check' },
    completed: { cls: 'alert-resolved', label: 'Completed', icon: 'check2-circle' },
    cancelled: { cls: 'b-gray',         label: 'Cancelled', icon: 'slash-circle' }
  }[status] || { cls: 'b-gray', label: status, icon: 'circle' }
}

function divisionBadge(d) {
  return { Regular: 'b-blue', Extension: 'b-purple', Both: 'b-brand' }[d] || 'b-gray'
}
function divisionIcon(d) {
  if (d === 'Extension') return 'bi-moon-stars'
  if (d === 'Both')      return 'bi-arrow-left-right'
  return 'bi-sun'
}
</script>

