    <Modal v-if="scheduleOpen"
           :title="draft?.id ? 'Schedule Makeup Class' : 'New Makeup Class'"
           subtitle="Set the replacement session details"
           @close="closeSchedule">
      <div class="row g-3">
        <!-- 1. Department -->
        <div class="col-md-6">
          <div class="form-row">
            <label>
              Department <span class="req">*</span>
              <span v-if="!isAdmin" class="t-xs muted" style="font-weight:400">
                · locked to your department
