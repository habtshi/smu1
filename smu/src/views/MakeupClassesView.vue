          <button :class="{ active: historyTab === 'cancelled' }" @click="historyTab = 'cancelled'; historyPage = 1">
            Cancelled ({{ cancelledRows.length }})
          </button>
        </div>
      </div>

      <!-- Search + Division filter -->
      <div class="tbl-toolbar">
        <div class="tbl-search">
